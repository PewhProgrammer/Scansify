	Matrix::Matrix(const Float4 & r1, const Float4 & r2, const Float4 & r3, const Float4 & r4)
	{
		f4[0] = r1;
		f4[1] = r2;
		f4[2] = r3;
		f4[3] = r4;
	}
	Float4 & Matrix::operator[](int idx)
	{
		return f4[idx];
	}
	Float4 Matrix::operator[](int idx) const
	{
		return f4[idx];
	}
	Matrix Matrix::operator+(const Matrix & b) const
	{
		return Matrix(
			Float4(f4[0][0] + b[0][0], f4[0][1] + b[0][1], f4[0][2] + b[0][2], f4[0][3] + b[0][3]),
			Float4(f4[1][0] + b[1][0], f4[1][1] + b[1][1], f4[1][2] + b[1][2], f4[1][3] + b[1][3]), 
			Float4(f4[2][0] + b[2][0], f4[2][1] + b[2][1], f4[2][2] + b[2][2], f4[2][3] + b[2][3]), 
			Float4(f4[3][0] + b[3][0], f4[3][1] + b[3][1], f4[3][2] + b[3][2], f4[3][3] + b[3][3]) );
	}
	Matrix Matrix::operator-(const Matrix & b) const
	{
		return Matrix(
			Float4(f4[0][0] - b[0][0], f4[0][1] - b[0][1], f4[0][2] - b[0][2], f4[0][3] - b[0][3]),
			Float4(f4[1][0] - b[1][0], f4[1][1] - b[1][1], f4[1][2] - b[1][2], f4[1][3] - b[1][3]),
			Float4(f4[2][0] - b[2][0], f4[2][1] - b[2][1], f4[2][2] - b[2][2], f4[2][3] - b[2][3]),
			Float4(f4[3][0] - b[3][0], f4[3][1] - b[3][1], f4[3][2] - b[3][2], f4[3][3] - b[3][3]));
	}
	Matrix Matrix::transpose() const
	{
		return Matrix(
			Float4(f4[0][0], f4[1][0], f4[2][0], f4[3][0]),
			Float4(f4[0][1], f4[1][1], f4[2][1], f4[3][1]),
			Float4(f4[0][2], f4[1][2], f4[2][2], f4[3][2]),
			Float4(f4[0][3], f4[1][3], f4[2][3], f4[3][3]));
	}
	Matrix Matrix::invert() const {
    Matrix result;
    const Matrix& m = *this;

    //Taken and modified from http://stackoverflow.com/questions/1148309/inverting-a-4x4-matrix
    result[0][0] = m[1][1] * m[2][2] * m[3][3] - m[1][1] * m[2][3] * m[3][2] - m[2][1] * m[1][2] * m[3][3] + m[2][1] * m[1][3] * m[3][2] + m[3][1] * m[1][2] * m[2][3] - m[3][1] * m[1][3] * m[2][2];
    result[1][0] = -m[1][0] * m[2][2] * m[3][3] + m[1][0] * m[2][3] * m[3][2] + m[2][0] * m[1][2] * m[3][3] - m[2][0] * m[1][3] * m[3][2] - m[3][0] * m[1][2] * m[2][3] + m[3][0] * m[1][3] * m[2][2];
    result[2][0] = m[1][0] * m[2][1] * m[3][3] - m[1][0] * m[2][3] * m[3][1] - m[2][0] * m[1][1] * m[3][3] + m[2][0] * m[1][3] * m[3][1] + m[3][0] * m[1][1] * m[2][3] - m[3][0] * m[1][3] * m[2][1];
    result[3][0] = -m[1][0] * m[2][1] * m[3][2] + m[1][0] * m[2][2] * m[3][1] + m[2][0] * m[1][1] * m[3][2] - m[2][0] * m[1][2] * m[3][1] - m[3][0] * m[1][1] * m[2][2] + m[3][0] * m[1][2] * m[2][1];

    float det = m[0][0] * result[0][0] + m[0][1] * result[1][0] + m[0][2] * result[2][0] + m[0][3] * result[3][0];
    if (det == 0)
        return Matrix::zero();

    result[0][1] = -m[0][1] * m[2][2] * m[3][3] + m[0][1] * m[2][3] * m[3][2] + m[2][1] * m[0][2] * m[3][3] - m[2][1] * m[0][3] * m[3][2] - m[3][1] * m[0][2] * m[2][3] + m[3][1] * m[0][3] * m[2][2];
    result[1][1] = m[0][0] * m[2][2] * m[3][3] - m[0][0] * m[2][3] * m[3][2] - m[2][0] * m[0][2] * m[3][3] + m[2][0] * m[0][3] * m[3][2] + m[3][0] * m[0][2] * m[2][3] - m[3][0] * m[0][3] * m[2][2];
    result[2][1] = -m[0][0] * m[2][1] * m[3][3] + m[0][0] * m[2][3] * m[3][1] + m[2][0] * m[0][1] * m[3][3] - m[2][0] * m[0][3] * m[3][1] - m[3][0] * m[0][1] * m[2][3] + m[3][0] * m[0][3] * m[2][1];
    result[3][1] = m[0][0] * m[2][1] * m[3][2] - m[0][0] * m[2][2] * m[3][1] - m[2][0] * m[0][1] * m[3][2] + m[2][0] * m[0][2] * m[3][1] + m[3][0] * m[0][1] * m[2][2] - m[3][0] * m[0][2] * m[2][1];
    result[0][2] = m[0][1] * m[1][2] * m[3][3] - m[0][1] * m[1][3] * m[3][2] - m[1][1] * m[0][2] * m[3][3] + m[1][1] * m[0][3] * m[3][2] + m[3][1] * m[0][2] * m[1][3] - m[3][1] * m[0][3] * m[1][2];
    result[1][2] = -m[0][0] * m[1][2] * m[3][3] + m[0][0] * m[1][3] * m[3][2] + m[1][0] * m[0][2] * m[3][3] - m[1][0] * m[0][3] * m[3][2] - m[3][0] * m[0][2] * m[1][3] + m[3][0] * m[0][3] * m[1][2];
    result[2][2] = m[0][0] * m[1][1] * m[3][3] - m[0][0] * m[1][3] * m[3][1] - m[1][0] * m[0][1] * m[3][3] + m[1][0] * m[0][3] * m[3][1] + m[3][0] * m[0][1] * m[1][3] - m[3][0] * m[0][3] * m[1][1];
    result[3][2] = -m[0][0] * m[1][1] * m[3][2] + m[0][0] * m[1][2] * m[3][1] + m[1][0] * m[0][1] * m[3][2] - m[1][0] * m[0][2] * m[3][1] - m[3][0] * m[0][1] * m[1][2] + m[3][0] * m[0][2] * m[1][1];
    result[0][3] = -m[0][1] * m[1][2] * m[2][3] + m[0][1] * m[1][3] * m[2][2] + m[1][1] * m[0][2] * m[2][3] - m[1][1] * m[0][3] * m[2][2] - m[2][1] * m[0][2] * m[1][3] + m[2][1] * m[0][3] * m[1][2];
    result[1][3] = m[0][0] * m[1][2] * m[2][3] - m[0][0] * m[1][3] * m[2][2] - m[1][0] * m[0][2] * m[2][3] + m[1][0] * m[0][3] * m[2][2] + m[2][0] * m[0][2] * m[1][3] - m[2][0] * m[0][3] * m[1][2];
    result[2][3] = -m[0][0] * m[1][1] * m[2][3] + m[0][0] * m[1][3] * m[2][1] + m[1][0] * m[0][1] * m[2][3] - m[1][0] * m[0][3] * m[2][1] - m[2][0] * m[0][1] * m[1][3] + m[2][0] * m[0][3] * m[1][1];
    result[3][3] = m[0][0] * m[1][1] * m[2][2] - m[0][0] * m[1][2] * m[2][1] - m[1][0] * m[0][1] * m[2][2] + m[1][0] * m[0][2] * m[2][1] + m[2][0] * m[0][1] * m[1][2] - m[2][0] * m[0][2] * m[1][1];

    result = result*(1.0f/det);
    return result;
}

	bool Matrix::operator==(const Matrix & b) const
	{
		return 
			(f4[0][0] == b[0][0]) & (f4[0][1] == b[0][1]) & (f4[0][2] == b[0][2]) & (f4[0][3] == b[0][3]) & 
			(f4[1][0] == b[1][0]) & (f4[1][1] == b[1][1]) & (f4[1][2] == b[1][2]) & (f4[1][3] == b[1][3]) &
			(f4[2][0] == b[2][0]) & (f4[2][1] == b[2][1]) & (f4[2][2] == b[2][2]) & (f4[2][3] == b[2][3]) &
			(f4[3][0] == b[3][0]) & (f4[3][1] == b[3][1]) & (f4[3][2] == b[3][2]) & (f4[3][3] == b[3][3]);
	}

	bool Matrix::operator!=(const Matrix & b) const
	{
		return !(*this == b);
	}

	Float4 Matrix::operator*(const Float4 & b) const
	{
		//http://www.euclideanspace.com/maths/algebra/matrix/transforms/index.htm
		Float4 result;

		result[0] = f4[0][0] * b[0] + f4[0][1] * b[1] + f4[0][2] * b[2] + f4[0][3] * b[3];
		result[1] = f4[1][0] * b[0] + f4[1][1] * b[1] + f4[1][2] * b[2] + f4[1][3] * b[3];
		result[2] = f4[2][0] * b[0] + f4[2][1] * b[1] + f4[2][2] * b[2] + f4[2][3] * b[3];
		result[3] = f4[3][0] * b[0] + f4[3][1] * b[1] + f4[3][2] * b[2] + f4[3][3] * b[3];

		return result;
	}

	Vector Matrix::operator*(const Vector & b) const
	{
		Float4 result = Float4(b);
		return Vector(*this * result);
	}

	Point Matrix::operator*(const Point & b) const
	{
		Float4 result = Float4(b);
		return Point(*this * result);
	}

	float Matrix::det() const
	{
		float a = f4[0][0] * (
			  f4[1][1] * (f4[2][2] * f4[3][3] - f4[2][3]*f4[3][2]) 
			- f4[1][2] * (f4[2][1] * f4[3][3] - f4[3][1] * f4[2][3]) 
			+ f4[1][3] * (f4[2][1] * f4[3][2] - f4[3][1] * f4[2][2]) );

		float b = -f4[0][1] * (
			  f4[1][0] * (f4[2][2] * f4[3][3] - f4[2][3] * f4[3][2])
			- f4[1][2] * (f4[2][0] * f4[3][3] - f4[3][0] * f4[2][3])
			+ f4[1][3] * (f4[2][0] * f4[3][2] - f4[3][0] * f4[2][2]));

		float c = f4[0][2] * (
			  f4[1][0] * (f4[2][1] * f4[3][3] - f4[3][1] * f4[2][3])
			- f4[1][1] * (f4[2][0] * f4[3][3] - f4[3][0] * f4[2][3])
			+ f4[1][3] * (f4[2][0] * f4[3][1] - f4[3][0] * f4[2][1]));

		float d = -f4[0][3] * (
			  f4[1][0] * (f4[2][1] * f4[3][2] - f4[3][1] * f4[2][2])
			- f4[1][1] * (f4[2][0] * f4[3][2] - f4[3][0] * f4[2][2])
			+ f4[1][2] * (f4[2][0] * f4[3][1] - f4[3][0] * f4[2][1]));

		return a - b + c - d ;
	}

	Matrix Matrix::zero()
	{
		Float4 result = Float4(0, 0, 0, 0);
		return Matrix(result,result,result,result);
	}

	Matrix Matrix::identity()
	{
		Float4 result0 = Float4(1, 0, 0, 0);
		Float4 result1 = Float4(0, 1, 0, 0);
		Float4 result2 = Float4(0, 0, 1, 0);
		Float4 result3 = Float4(0, 0, 0, 1);

		return Matrix(result0,result1,result2,result3);
	}

	Matrix Matrix::system(const Vector & e1, const Vector & e2, const Vector & e3)
	{
		return Matrix(Float4(e1), Float4(e2), Float4(e3), Float4(0,0,0,1));;
	}

	Matrix product(const Matrix & a, const Matrix & b)
	{
		Matrix result;

		result[0][0] = a[0][0] * b[0][0] + a[0][1] * b[1][0] + a[0][2] * b[2][0] + a[0][3] * b[3][0];
		result[1][0] = a[0][0] * b[0][1] + a[0][1] * b[1][1] + a[0][2] * b[2][1] + a[0][3] * b[3][1];
		result[2][0] = a[0][0] * b[0][2] + a[0][1] * b[1][2] + a[0][2] * b[2][2] + a[0][3] * b[3][2];
		result[3][0] = a[0][0] * b[0][3] + a[0][1] * b[1][3] + a[0][2] * b[2][3] + a[0][3] * b[3][3];

		result[0][1] = a[1][0] * b[0][0] + a[1][1] * b[1][0] + a[1][2] * b[2][0] + a[1][3] * b[3][0];
		result[1][1] = a[1][0] * b[0][1] + a[1][1] * b[1][1] + a[1][2] * b[2][1] + a[1][3] * b[3][1];
		result[2][1] = a[1][0] * b[0][2] + a[1][1] * b[1][2] + a[1][2] * b[2][2] + a[1][3] * b[3][2];
		result[3][1] = a[1][0] * b[0][3] + a[1][1] * b[1][3] + a[1][2] * b[2][3] + a[1][3] * b[3][3];

		result[0][2] = a[2][0] * b[0][0] + a[2][1] * b[1][0] + a[2][2] * b[2][0] + a[2][3] * b[3][0];
		result[1][2] = a[2][0] * b[0][1] + a[2][1] * b[1][1] + a[2][2] * b[2][1] + a[2][3] * b[3][1];
		result[2][2] = a[2][0] * b[0][2] + a[2][1] * b[1][2] + a[2][2] * b[2][2] + a[2][3] * b[3][2];
		result[3][2] = a[2][0] * b[0][3] + a[2][1] * b[1][3] + a[2][2] * b[2][3] + a[2][3] * b[3][3];

		result[0][3] = a[3][0] * b[0][0] + a[3][1] * b[1][0] + a[3][2] * b[2][0] + a[3][3] * b[3][0];
		result[1][3] = a[3][0] * b[0][1] + a[3][1] * b[1][1] + a[3][2] * b[2][0] + a[3][3] * b[3][1];
		result[2][3] = a[3][0] * b[0][2] + a[3][1] * b[1][2] + a[3][2] * b[2][0] + a[3][3] * b[3][2];
		result[3][3] = a[3][0] * b[0][3] + a[3][1] * b[1][3] + a[3][2] * b[2][0] + a[3][3] * b[3][3];

		return result;
	}

	Matrix operator*(const Matrix & a, float scalar)
	{
		
		return Matrix(a[0]*scalar, a[1] * scalar, a[2] * scalar, a[3] * scalar);
	}

	Matrix operator*(float scalar, const Matrix & a)
	{
		return a * scalar;
	}

